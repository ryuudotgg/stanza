import { readFileSync } from "node:fs";
import { join } from "node:path";
import { columns } from "../src/engine/doc.ts";

const root = join(import.meta.dir, "..");
const BUN = readFileSync(join(root, ".bun-version"), "utf8").trim();
const engine = join(root, "crates", "stanza", "src", "engine");

const SAMPLE = [
  "plain ascii",
  "漢字かなカナ",
  "ｱｲｳ half width",
  "Ａ full width",
  "한국어",
  "😀 emoji",
  "👍🏽 skin tone",
  "👨‍👩‍👧 zero width joiner",
  "🇯🇵 flag",
  "❤️ variation selector",
  "é combining acute",
  "́ lone combining mark",
  "กั thai mark",
  "​ zero width space",
  "­ soft hyphen",
  "\u0085 next line",
  "\u009b control sequence introducer",
  "\u0080\u009f C1 bounds",
  "\u0007 bell",
  "\u001b[31m escape",
  "\t",
  "\t\t",
  "a\tb",
  "ab\tc",
  "abc\td",
  "漢\t字",
  "😀\tx",
  "  \t  if (x) return;",
];

if (Bun.version !== BUN) {
  console.error(`widths: run this with Bun ${BUN}, the version CI runs; this is ${Bun.version}`);
  process.exit(2);
}

const ranges: [number, number, number][] = [];
for (let point = 0; point <= 0x10ffff; point++) {
  if (point >= 0xd800 && point <= 0xdfff) continue;

  const width = Bun.stringWidth(String.fromCodePoint(point));
  if (width === 1) continue;

  const last = ranges.at(-1);
  if (last && last[1] === point - 1 && last[2] === width) last[1] = point;
  else ranges.push([point, point, width]);
}

const hex = (point: number) => `0x${point.toString(16)}`;
const table = ranges.map(([first, last, width]) => `    (${hex(first)}, ${hex(last)}, ${width}),`);
await Bun.write(
  join(engine, "widths.rs"),
  `// Generated by bun scripts/widths.ts from Bun ${BUN}'s Bun.stringWidth. Do not edit.\n\npub const WIDTHS: &[(u32, u32, u8)] = &[\n${table.join("\n")}\n];\n`,
);

const sample = SAMPLE.flatMap((text) =>
  [2, 4].map((tab) => ({ text, tab, columns: columns(text, tab) })),
);

await Bun.write(join(engine, "columns.json"), `${JSON.stringify(sample, null, 2)}\n`);

console.log(`widths: ${ranges.length} ranges, ${sample.length} samples`);
